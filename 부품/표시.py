"""
읽은 글자에 확신 표시(⟪⟫)를 붙이고 열마다 한 줄 글월로 — `step4_read` · `읽기.py` · Toolforge 서버(`툴포지/`)가 함께 씀.
(2026-10-07 `step4_read.py` 에서 그대로 옮김 — torch 없이 불러올 수 있게. `step4_read` 는 이 이름들을 다시 내보냄)
브라우저판 짝: `읽기.js` 의 `확신표시` · `줄글월`.
"""
import unicodedata


def as_text(seq):
    """사람이 읽기 좋게. 현대 글자는 완성형으로 합쳐 준다."""
    return unicodedata.normalize("NFC", "".join(seq))


안쪽, 바깥 = "⟪", "⟫"          # 옛한글 전사문에 안 나오는 글자라야 지우기 쉽다
표시문턱 = 0.93                 # 확신이 이보다 낮으면 ⟪⟫ — 2026-09-27 0.7 → 0.8, 2026-09-28 0.9, 2026-10-07 0.93(문장부호 증류 모델 — 확신값이 0.96 언저리에서 멈춰 0.95 넘게 올리면 거의 다 표시됨). 읽기.py·브라우저판(설정.json)이 이 값을 씀


def 확신표시(hyp, conf, 문턱=표시문턱, 빈=None):
    """
    확신이 낮은 글자를 `⟪…⟫` 로 감싼 글월과, 감싼 글자 수.

    ★ **왜 이것이 CER 을 낮추는 것보다 값어치가 있는가** — 이 도구의 쓰임은
    '사람이 결과를 보고 고치는 것'이고, 그때 가장 큰 품은 **어디가 틀렸는지
    찾는 것**입니다. 실측(문헌 여섯·13,210자, '못씀' 쪽 제외):

    | 확신 낮은 것부터 볼 비율 | 찾는 오류 | 본 것 중 오류 |
    |---|---|---|
    | 5%  | **62%** | 86% |
    | 10% | **83%** | 58% |
    | 15% | **90%** | 42% |
    | 30% | 94% | 22% |

    **글자의 15% 만 보면 오류의 90% 를 찾습니다.** 그 표본의 오류율이
    7.0% 였으니 남는 오류가 0.7% 입니다.

    문턱 0.7 이 16% 를 표시하고 90% 를 잡습니다(0.5 는 8%/77%, 0.8 은 28%/93%).
    ★ 2026-09-26 증류 모델(떼어 둔 쪽, 실험18): 0.7 은 5% 표시·남는 오류 0.70%,
      **0.8 은 9% 표시·남는 오류 약 0.47%** → 2026-09-27 기본값을 0.8 로 올림.

    ⚠ **'못씀' 쪽은 빼고 잰 값입니다.** 그 쪽들까지 넣으면 확신도가 실제보다
      좋아 보입니다 — 실전에서는 사람이 그 쪽을 아예 안 보므로 이렇게 재는
      것이 맞습니다.
    """
    조각, 셀, 켬 = [], 0, False
    for k, (ch, c) in enumerate(zip(hyp, conf)):
        낮 = c < 문턱
        if 낮 and not 켬:
            조각.append(안쪽); 켬 = True
        elif not 낮 and 켬:
            조각.append(바깥); 켬 = False
        조각.append(ch); 셀 += 낮
        if 빈 and 빈[k]:                 # 띄어쓰기(2026-09-29) — ⟪⟫ 는 빈칸을 감싸지 않는다
            if 켬:
                조각.append(바깥); 켬 = False
            조각.append(" ")
    if 켬:
        조각.append(바깥)
    return as_text(조각), 셀


def 띄운글(hyp, 빈=None):
    """글자들을 이어 붙이되 빈[k] 가 참인 글자 뒤를 띄운다."""
    return as_text([ch + (" " if 빈 and 빈[k] else "") for k, ch in enumerate(hyp)])


def 줄글월(줄들, 문턱=표시문턱):
    """
    열마다 한 줄로 — 원문의 줄바꿈을 살린다. `align.read_page_lines` 의 결과를 받는다
    ((글자, 확신) 또는 띄어쓰기까지 (글자, 확신, 빈칸) — `띄움=True`).
    반환: (표시 없는 글월, ⟪⟫ 표시한 글월, 표시한 글자 수)

    ★ 표시는 **줄마다 따로** 붙인다. ⟪…⟫ 가 줄을 넘어가면 지우기 번거롭다.
    ⚠ 위키문헌에서 줄바꿈 하나는 **띄어쓰기로 보입니다.** 저장 전에 줄을
      이어야 할 수 있습니다(열 끝이 낱말 한가운데일 때가 많음).
    """
    글, 표, 셀 = [], [], 0
    for 줄 in 줄들:
        hyp, conf = 줄[0], 줄[1]
        빈 = 줄[2] if len(줄) > 2 else None
        s, n = 확신표시(hyp, conf, 문턱, 빈)
        글.append(띄운글(hyp, 빈)); 표.append(s); 셀 += n
    return "\n".join(글), "\n".join(표), 셀
